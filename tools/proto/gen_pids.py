#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_pids.py
===========
为 protocol/proto 下的每个 message 分配唯一协议号，生成 protocol/pids.lua。

规则：
    * 一个 message 一个唯一 id
    * 每个 message 两个条目：
        [id]        = "package.message"
        ["package.message"] = id

id 由 crc32(fullname) 生成，确定性、与文件顺序无关；冲突时线性探测。

用法：
    python sro/tools/proto/gen_pids.py
    python sro/tools/proto/gen_pids.py --check
"""

from __future__ import annotations

import argparse
import re
import zlib
from pathlib import Path

PACKAGE_RE = re.compile(r"^\s*package\s+([\w.]+)\s*;", re.M)
MSG_RE = re.compile(r"^\s*message\s+(\w+)", re.M)


def collect_messages(proto_dir: Path) -> list[str]:
    names: list[str] = []
    for path in sorted(proto_dir.glob("*.proto")):
        text = path.read_text(encoding="utf-8", errors="replace")
        m = PACKAGE_RE.search(text)
        package = m.group(1) if m else ""
        for msg in MSG_RE.findall(text):
            full = f"{package}.{msg}" if package else msg
            names.append(full)
    return sorted(set(names))


def assign_ids(names: list[str]) -> dict[str, int]:
    used: set[int] = set()
    result: dict[str, int] = {}
    for name in names:
        pid = zlib.crc32(name.encode("utf-8")) & 0xFFFFFFFF
        if pid == 0:
            pid = 1
        while pid in used:
            pid = (pid + 1) & 0xFFFFFFFF
            if pid == 0:
                pid = 1
        used.add(pid)
        result[name] = pid
    return result


def main() -> int:
    here = Path(__file__).resolve()
    default_root = here.parents[2]  # sro/
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(default_root))
    ap.add_argument("--proto-dir", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    proto_dir = Path(args.proto_dir).resolve() if args.proto_dir else root / "protocol" / "proto"
    out = Path(args.out).resolve() if args.out else root / "protocol" / "pids.lua"

    names = collect_messages(proto_dir)
    mapping = assign_ids(names)

    if args.check:
        print(f"messages={len(names)} ids={len(set(mapping.values()))}")
        return 0 if len(mapping) == len(set(mapping.values())) else 1

    lines = [
        "-- Auto-generated by sro/tools/proto/gen_pids.py. DO NOT EDIT.",
        "-- 每个 message 一个唯一 id；双向映射",
        "return {",
    ]
    for name in names:
        pid = mapping[name]
        lines.append(f'["{name}"]={pid},')
        lines.append(f"[{pid}]=\"{name}\",")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"messages={len(names)} entries={len(names)*2} written={out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
