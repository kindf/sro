#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_protos.py
=============
扫描 protocol/proto/*.proto，按 import 依赖生成 protocol/protos.lua。

protos.lua 与 pids.lua 同级，内容是按依赖排序的 proto 基名：

    return {
        "common",
        "move",
        "scene",
    }

加载端按顺序把 `<name>.pb` 交给 pb.loadfile，避免依赖未加载。

用法：
    python sro/tools/proto/gen_protos.py
    python sro/tools/proto/gen_protos.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

IMPORT_RE = re.compile(r'^\s*import\s+"([^"]+)"', re.M)


def topo_sort(files: dict[str, list[str]]) -> list[str]:
    order: list[str] = []
    state: dict[str, int] = {}  # 1=visiting, 2=done

    def visit(name: str) -> None:
        s = state.get(name, 0)
        if s == 2:
            return
        if s == 1:
            raise SystemExit(f"import cycle: {name}")
        state[name] = 1
        for dep in files[name]:
            if dep in files:
                visit(dep)
        state[name] = 2
        order.append(name)

    for name in sorted(files):
        visit(name)
    return order


def main() -> int:
    here = Path(__file__).resolve()
    default_root = here.parents[2]  # sro/
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(default_root))
    ap.add_argument("--proto-dir", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    proto_dir = Path(args.proto_dir).resolve() if args.proto_dir else root / "protocol" / "proto"
    out = Path(args.out).resolve() if args.out else root / "protocol" / "protos.lua"

    files: dict[str, list[str]] = {}
    warnings: list[str] = []

    for path in sorted(proto_dir.glob("*.proto")):
        text = path.read_text(encoding="utf-8", errors="replace")
        deps = []
        for imp in IMPORT_RE.findall(text):
            if imp.startswith("google/"):
                continue
            dep = Path(imp).stem
            if not (proto_dir / f"{dep}.proto").exists():
                warnings.append(f"{path.name}: missing import {imp}")
                continue
            deps.append(dep)
        files[path.stem] = deps

    order = topo_sort(files)

    if args.check:
        for w in warnings:
            print("WARN", w)
        print(f"protos={len(order)} order={order}")
        return 0 if not warnings else 1

    lines = [
        "-- Auto-generated by sro/tools/proto/gen_protos.py. DO NOT EDIT.",
        "-- 按 import 依赖排序，加载时先加载前面的",
        "return {",
    ]
    for name in order:
        lines.append(f'"{name}",')
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    for w in warnings:
        print("WARN", w, file=sys.stderr)
    print(f"protos={len(order)} written={out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
