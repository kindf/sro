#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
prune_generated.py
==================
按 keep_tables.txt 裁剪 gamedata/generated，并重写 allconfigfiles.lua。

用途：课程只保留当前用到的配置表；需要新表时，先重新生成全量，再把表名
加进 keep_tables.txt，跑一次本脚本。

用法：
    python sro/tools/table/prune_generated.py
    python sro/tools/table/prune_generated.py --dry-run
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> int:
    here = Path(__file__).resolve()
    sro = here.parents[2]

    ap = argparse.ArgumentParser()
    ap.add_argument("--keep-file", default=str(sro / "gamedata" / "keep_tables.txt"))
    ap.add_argument("--generated", default=str(sro / "gamedata" / "generated"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    keep_path = Path(args.keep_file)
    gen_dir = Path(args.generated)

    keep = []
    for line in keep_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            keep.append(line)
    keep = sorted(set(keep))

    existing = {p.stem for p in gen_dir.glob("tb*.lua")}
    missing = [name for name in keep if name not in existing]
    if missing:
        print("ERROR missing generated tables:", ", ".join(missing))
        return 1

    removed = []
    for name in sorted(existing):
        if name not in keep:
            path = gen_dir / f"{name}.lua"
            if args.dry_run:
                removed.append(name)
            else:
                path.unlink()
                removed.append(name)

    lines = [
        "-- Auto-generated by sro/tools/table/prune_generated.py. DO NOT EDIT.",
        f"-- {len(keep)} tables",
        "return {",
    ]
    for name in keep:
        lines.append(f'"{name}",')
    lines.append("}")
    content = "\n".join(lines) + "\n"

    if args.dry_run:
        print(f"keep={len(keep)} remove={len(removed)} (dry-run)")
        print("removed:", ", ".join(removed[:10]), "..." if len(removed) > 10 else "")
    else:
        (gen_dir / "allconfigfiles.lua").write_text(content, encoding="utf-8")
        print(f"keep={len(keep)} removed={len(removed)}")
        print("kept:", ", ".join(keep))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
